#!/usr/bin/env python3
"""Run the verbatim pinned upstream distance kernel using a minimal vector shim.

No network, Eigen, CMake or upstream viewer is needed. Generate a checked-in
MoonBit differential fixture with --update, or verify it with the default mode.
"""
from pathlib import Path
import argparse
import hashlib
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/PositionBasedDynamics/PositionBasedDynamics/XPBD.cpp'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--update', action='store_true')
    args = parser.parse_args()
    source = SOURCE.read_text()
    begin = source.index('bool XPBD::solve_DistanceConstraint(')
    end = source.index('// ----------------------------------------------------------------------------------------------', begin)
    kernel = source[begin:end].replace('XPBD::solve_DistanceConstraint', 'solve_distance')
    shim = r'''
#include <cmath>
#include <iostream>
#include <iomanip>
using Real = double;
struct Vector3r {
  double x, y, z;
  Vector3r operator-(Vector3r b) const { return {x-b.x,y-b.y,z-b.z}; }
  Vector3r& operator/=(double k) { x/=k; y/=k; z/=k; return *this; }
  double norm() const { return std::sqrt(x*x+y*y+z*z); }
  void setZero() { x=y=z=0; }
};
Vector3r operator*(Vector3r a, double k) { return {a.x*k,a.y*k,a.z*k}; }
Vector3r operator*(double k, Vector3r a) { return a*k; }
'''
    cases = []
    for i in range(40):
        x0, y0 = 0.13 * i, -0.07 * i
        x1, y1 = x0 + 0.5 + (i % 7) * 0.3, y0 + 0.4 + (i % 5) * 0.17
        mass0, mass1 = (0.0 if i % 4 == 0 else 0.5 + i % 3), 0.7 + (i % 5) * 0.4
        rest = 0.2 + (i % 6) * 0.21
        compliance = 0.0 if i % 3 == 0 else 0.0001 * (i % 9 + 1)
        dt = 0.01 + (i % 5) * 0.015
        cases.append((x0, y0, x1, y1, mass0, mass1, rest, compliance, dt))
    body = ['int main() { std::cout << std::setprecision(17);']
    for x0, y0, x1, y1, m0, m1, rest, compliance, dt in cases:
        body.append('''{ Vector3r a{%r,%r,0}, b{%r,%r,0}, ca{}, cb{}; Real l=0;
solve_distance(a,%r,b,%r,%r,%r,%r,l,ca,cb);
std::cout << a.x+ca.x << " " << a.y+ca.y << " " << b.x+cb.x << " " << b.y+cb.y << "\\n"; }''' %
                    (x0,y0,x1,y1,0 if m0 == 0 else 1/m0,1/m1,rest,0 if compliance == 0 else 1/compliance,dt))
    body.append('}')
    compiler = shutil.which('g++') or shutil.which('clang++')
    if not compiler:
        raise SystemExit('A C++ compiler is required for reference verification only')
    with tempfile.TemporaryDirectory() as directory:
        cpp = Path(directory) / 'reference.cpp'
        exe = Path(directory) / 'reference'
        cpp.write_text(shim + kernel + '\n' + '\n'.join(body))
        subprocess.run([compiler, '-std=c++11', '-O2', str(cpp), '-o', str(exe)], check=True)
        rows = subprocess.check_output([str(exe)], text=True).splitlines()
    lines = ['// Generated by scripts/upstream_reference.py --update.',
             '// Verbatim pinned upstream distance kernel, 40 configurations.',
             '///|', 'test "distance projection matches upstream C++ in 40 configurations" {']
    for case, row in zip(cases, rows):
        x0,y0,x1,y1,m0,m1,rest,compliance,dt = case
        ax,ay,bx,by = map(float,row.split())
        f = lambda n: repr(float(n))
        lines.extend([
            '  {',
            '    let w = World::new(config=Config::new(gravity=Vec2::new(0.0, 0.0), substeps=1, iterations=1, damping=0.0))',
            f'    let a = w.add_particle(Vec2::new({f(x0)}, {f(y0)}), mass={f(m0)})',
            f'    let b = w.add_particle(Vec2::new({f(x1)}, {f(y1)}), mass={f(m1)})',
            f'    ignore(w.add_distance(a, b, rest_length={f(rest)}, compliance={f(compliance)}))',
            f'    ignore(w.step({f(dt)}))',
            f'    assert_true((w.position(a).x - ({f(ax)})).abs() < 0.000000001)',
            f'    assert_true((w.position(a).y - ({f(ay)})).abs() < 0.000000001)',
            f'    assert_true((w.position(b).x - ({f(bx)})).abs() < 0.000000001)',
            f'    assert_true((w.position(b).y - ({f(by)})).abs() < 0.000000001)',
            '  }'])
    lines.extend(['}', ''])
    # Format through moon fmt before comparing, so the fixture shares repo style.
    output = ROOT / 'upstream_distance_wbtest.mbt'
    if args.update:
        output.write_text('\n'.join(lines))
        print('Updated 40-case differential fixture; run moon fmt and moon test.')
    else:
        # Verify all expected coordinate tuples independently of MoonBit formatting.
        import re
        expected = re.findall(r'position\([ab]\)\.[xy]\s*-\s*\(?\s*(-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)', output.read_text())
        current = [float(x) for row in rows for x in row.split()]
        if len(expected) != len(current) or any(abs(float(a)-b) > 1e-12 for a,b in zip(expected,current)):
            raise SystemExit('Pinned C++ output differs from committed fixture')
        print('Verified 40 C++ reference cases / 160 coordinate values; source SHA256=' + hashlib.sha256(SOURCE.read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
